/*延时1ms*/
void delay_ms(uint16_t ms)
{
#if (MCU_TYPE == MCU_TYPE_STM32)
    HAL_Delay(ms);
#elif (MCU_TYPE == MCU_TYPE_HC32_F0 || MCU_TYPE == MCU_TYPE_HC32_L1)
    Ddl_Delay1ms(ms);
#elif (MCU_TYPE == MCU_TYPE_HC32_F4)
    Ddl_Delay1ms(ms);
#endif
}
/*延时1us*/
void delay_us(uint16_t us)
{
#if (MCU_TYPE == MCU_TYPE_STM32)

#elif (MCU_TYPE == MCU_TYPE_HC32_F0 || MCU_TYPE == MCU_TYPE_HC32_L1)
    Ddl_Delay1us(us);
#elif (MCU_TYPE == MCU_TYPE_HC32_F4)
    Ddl_Delay1us(us);
#endif
}
